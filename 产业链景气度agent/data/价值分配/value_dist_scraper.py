# 去除 代码_override 字段，统一用 代码 列
def normalize_map(raw_list):
    result = []
    for item in raw_list:
        row = {k: v for k, v in item.items() if k != "代码_override"}
        if "代码_override" in item:
            row["代码"] = item["代码_override"]
        result.append(row)
    return result

