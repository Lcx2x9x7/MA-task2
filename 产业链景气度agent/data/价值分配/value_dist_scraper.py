# 2. 按产业链 × 层级展示利润率分布（不聚合为单一指标）
# ══════════════════════════════════════════════════════════════════

def build_layer_margin(company_df):
    print("\n[2/3] 构建层级利润率分布...")

    if company_df.empty:
        print("  [SKIP] 无公司财务数据")
        return pd.DataFrame()

    # 只取最新一期（按报告期倒排）
    company_df = company_df.copy()
    company_df["报告期"] = pd.to_datetime(company_df["报告期"], errors="coerce")
    latest = (
        company_df.dropna(subset=["报告期"])
        .sort_values("报告期", ascending=False)
        .groupby(["股票代码", "节点"])
        .first()
        .reset_index()
    )
    latest["报告期_str"] = latest["报告期"].dt.strftime("%Y-%m-%d")

    # 生成：每个公司在每个产业链×层级×上中下游中的利润率（不聚合）
    # 列：产业链, 上中下游, 节点, 股票代码, 公司名称, 报告期, 毛利率%, 净利率%, ROE_%
    cols = ["产业链", "上中下游", "层级", "节点", "股票代码", "公司名称",
            "报告期_str", "毛利率%", "净利率%", "ROE_%", "ROE加权%"]
    result = latest[[c for c in cols if c in latest.columns]].copy()
    result = result.rename(columns={"报告期_str": "最新报告期"})
    result = result.sort_values(["产业链", "上中下游", "毛利率%"], ascending=[True, True, False])

    out = os.path.join(OUTDIR, "layer_margin.csv")
    result.to_csv(out, index=False, encoding="utf-8-sig")
    print(f"  [OK] 输出 {len(result)} 行 → {out}")
    return result


